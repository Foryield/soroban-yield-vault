#!/usr/bin/env bash
# Archivage hors chaine des transactions de preuve SCF.
#
# Pourquoi : le reset du testnet SDF (prochain annonce les 16-17/12/2026)
# efface le ledger, et Stellar Expert testnet avec lui. Tout hash consigne dans
# docs/evidence/ devient alors un lien mort. Ce script fige, le jour ou la
# preuve est produite, ce qu'un reviewer pourrait encore verifier sans le
# reseau : la transaction brute (Horizon et Stellar Expert), sa version decodee
# (enveloppe, resultat, meta avec les events) et une capture de la page
# Stellar Expert.
#
# Sortie, un dossier par transaction :
#   docs/evidence/archive/<livrable>/<hash>/
#     horizon.json         reponse brute de Horizon testnet
#     stellar-expert.json  reponse brute de l'API Stellar Expert (XDR base64)
#     decoded.json         enveloppe, resultat et meta decodes par `stellar xdr`
#     stellar-expert.png   capture de la page Stellar Expert
# puis l'index docs/evidence/archive/INDEX.md est regenere.
#
# Idempotent : un dossier deja complet est saute (FORCE=1 pour refaire).
# Lecture seule cote reseau : rien n'est signe ni soumis.
#
# Usage : scripts/archive_proof.sh <livrable> <tx_hash>   (ex. d4 13b86dd9...)
#         scripts/archive_proof.sh --from-logs
#
# --from-logs archive chaque lien Stellar Expert `tx/<hash>` des journaux
# docs/evidence/d<N>-*.md, le livrable etant deduit du nom du journal.
#
# Variables d'environnement :
#   FORCE=1   refaire les dossiers deja complets
#   CHROME    navigateur pour la capture (defaut : Google Chrome macOS)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ARCHIVE="$ROOT/docs/evidence/archive"
HORIZON=https://horizon-testnet.stellar.org
EXPERT_API=https://api.stellar.expert/explorer/testnet
EXPERT_WEB=https://stellar.expert/explorer/testnet
CHROME="${CHROME:-/Applications/Google Chrome.app/Contents/MacOS/Google Chrome}"
FILES=(horizon.json stellar-expert.json decoded.json stellar-expert.png)

archive_one() {
  local deliverable="$1" hash="$2"
  [[ "$deliverable" =~ ^d[1-6]$ ]] || { echo "livrable invalide : $deliverable" >&2; return 1; }
  [[ "$hash" =~ ^[0-9a-f]{64}$ ]] || { echo "hash invalide : $hash" >&2; return 1; }

  local dir="$ARCHIVE/$deliverable/$hash" complete=1 f
  for f in "${FILES[@]}"; do [ -s "$dir/$f" ] || complete=0; done
  if [ "$complete" -eq 1 ] && [ "${FORCE:-0}" != 1 ]; then
    echo "deja archive : $deliverable/$hash"
    return 0
  fi
  mkdir -p "$dir"

  # -f : un 404 (transaction inconnue, reseau deja reinitialise) fait echouer
  # au lieu d'archiver une page d'erreur. L'API Stellar Expert limite le debit
  # (429 apres une quinzaine de transactions d'affilee) : les reprises espacees
  # laissent la fenetre se rouvrir au lieu d'abandonner le lot.
  local fetch=(curl -sf --retry 6 --retry-delay 20 --retry-all-errors)
  "${fetch[@]}" "$HORIZON/transactions/$hash" -o "$dir/horizon.json"
  "${fetch[@]}" "$EXPERT_API/tx/$hash" -o "$dir/stellar-expert.json"

  python3 -I - "$dir" <<'PY'
import json, subprocess, sys
d = sys.argv[1]
raw = json.load(open(f"{d}/stellar-expert.json"))
def decode(xdr_type, b64):
    out = subprocess.run(
        ["stellar", "xdr", "decode", "--type", xdr_type,
         "--input", "single-base64", "--output", "json"],
        input=b64, capture_output=True, text=True, check=True)
    return json.loads(out.stdout)
decoded = {
    "hash": raw["hash"],
    "ledger": raw["ledger"],
    "envelope": decode("TransactionEnvelope", raw["body"]),
    "result": decode("TransactionResult", raw["result"]),
    "meta": decode("TransactionMeta", raw["meta"]),
}
json.dump(decoded, open(f"{d}/decoded.json", "w"), indent=1)
PY

  # La page Stellar Expert est rendue cote client : le budget de temps virtuel
  # laisse ses appels d'API aboutir avant la capture.
  "$CHROME" --headless=new --disable-gpu --hide-scrollbars \
    --window-size=1440,1100 --virtual-time-budget=15000 \
    --screenshot="$dir/stellar-expert.png" "$EXPERT_WEB/tx/$hash" 2>/dev/null
  [ -s "$dir/stellar-expert.png" ] || { echo "capture absente : $hash" >&2; return 1; }

  echo "archive : $deliverable/$hash"
}

write_index() {
  python3 -I - "$ARCHIVE" <<'PY'
import json, pathlib, sys
root = pathlib.Path(sys.argv[1])
rows = []
for h in sorted(root.glob("d*/*/horizon.json")):
    tx = json.load(open(h))
    rows.append((h.parent.parent.name, tx["created_at"], tx["hash"],
                 tx["ledger"], "yes" if tx["successful"] else "no"))
rows.sort(key=lambda r: (r[0], r[1]))
lines = [
    "# Archived proof transactions",
    "",
    "Generated by `scripts/archive_proof.sh`, do not edit by hand. Each row",
    "links to a folder holding the raw Horizon and Stellar Expert responses,",
    "the decoded envelope, result and meta (events included) and a Stellar",
    "Expert screenshot, so every proof stays checkable after a testnet reset.",
    "",
    "| Deliverable | Date (UTC) | Ledger | Successful | Transaction |",
    "|---|---|---|---|---|",
]
for d, ts, h, ledger, ok in rows:
    lines.append(f"| {d.upper()} | {ts} | {ledger} | {ok} | [`{h[:12]}...`]({d}/{h}/) |")
(root / "INDEX.md").write_text("\n".join(lines) + "\n")
print(f"index : {len(rows)} transactions")
PY
}

if [ "${1:-}" = "--from-logs" ]; then
  for log in "$ROOT"/docs/evidence/d[1-6]-*.md; do
    deliverable="$(basename "$log" | cut -c1-2)"
    for hash in $(grep -oE 'tx/[0-9a-f]{64}' "$log" | cut -c4- | sort -u); do
      archive_one "$deliverable" "$hash"
    done
  done
else
  archive_one "${1:?usage: archive_proof.sh <livrable> <tx_hash> | --from-logs}" \
    "${2:?hash de transaction}"
fi
write_index
